async function main() {
  console.log('Iniciant seed inventari Orbita Events...');
  console.log(`Items a processar: ${items.length}`);
  console.log('---');

  let created = 0;
  let updated = 0;

  for (const item of items) {
    const result = await prisma.inventoryItem.upsert({
      where: { code: item.code },
      update: {
        name: item.name,
        description: item.description,
        category: item.category,
        watts: item.watts,
        value: item.value,
        status: item.status,
        condition: item.condition,
        isConsumable: item.isConsumable,
        stockQuantity: item.stockQuantity,
        minStock: item.minStock,
        purchaseDate: item.purchaseDate,
        purchasePrice: item.purchasePrice,
        expectedLifeHours: item.expectedLifeHours,
        notes: item.notes,
      },
      create: {
        code: item.code,
        name: item.name,
        description: item.description,
        category: item.category,
        watts: item.watts,
        value: item.value,
        status: item.status,
        condition: item.condition,
        isConsumable: item.isConsumable,
        stockQuantity: item.stockQuantity,
        minStock: item.minStock,
        purchaseDate: item.purchaseDate,
        purchasePrice: item.purchasePrice,
        expectedLifeHours: item.expectedLifeHours,
        notes: item.notes,
      },
    });

    // Check if it was newly created (createdAt equals updatedAt roughly)
    const isNew = Math.abs(result.createdAt.getTime() - result.updatedAt.getTime()) < 1000;
    if (isNew) {
      created++;
      console.log(`  [CREAT]      ${item.code} — ${item.name}`);
    } else {
      updated++;
      console.log(`  [ACTUALITZAT] ${item.code} — ${item.name}`);
    }
  }

  console.log('---');
  console.log(`Resultat: ${created} creats, ${updated} actualitzats, ${items.length} total`);

  // Show summary by category
  const summary = await prisma.inventoryItem.groupBy({
    by: ['category'],
    _count: { id: true },
    _sum: { value: true },
  });

  console.log('\nResum per categoria:');
  for (const row of summary) {
    console.log(`  ${row.category.padEnd(16)} ${row._count.id} items — valor total: ${row._sum.value?.toFixed(2)}€`);
  }

  const totalValue = summary.reduce((acc, r) => acc + (r._sum.value || 0), 0);
  console.log(`\n  TOTAL: ${summary.reduce((a, r) => a + r._count.id, 0)} items — ${totalValue.toFixed(2)}€ valor inventari`);
}

main()
  .catch((e) => {
    console.error('Error durant el seed:', e);
    process.exit(1);
  })
  .finally(() => prisma.$disconnect());
